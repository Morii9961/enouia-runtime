import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const read = path => readFileSync(resolve(root, path), 'utf8');
const retired = ['activity_call', 'activity_setup', 'usage_call', 'usage_pick', 'usage_cancel'];
const main = read('apps/desktop/src-tauri/src/main.rs');
const build = read('apps/desktop/src-tauri/build.rs');
const shell = read('apps/desktop/src-tauri/src/shell.rs');
for (const command of retired) {
  assert(!main.includes(`::${command}`), `registered retired command: ${command}`);
  assert(!build.includes(`"${command}"`), `declared retired command: ${command}`);
}
const generated = readdirSync(resolve(root, 'apps/desktop/src-tauri/permissions/autogenerated'));
for (const command of retired) assert(!generated.includes(`${command}.toml`), `retired permission generated: ${command}`);
assert(!/mod (activity|usage|usage_wire);/.test(main), 'retired native modules still compile');
assert(!/ActivityHost|UsageHost/.test(main + shell), 'retired host lifecycle remains');
for (const name of readdirSync(resolve(root, 'apps/desktop/src-tauri/capabilities'))) {
  const capability = JSON.parse(read(`apps/desktop/src-tauri/capabilities/${name}`));
  for (const permission of capability.permissions) {
    assert(!/^allow-(activity|usage)-/.test(typeof permission === 'string' ? permission : permission.identifier));
  }
}
assert(main.includes('memory::memory_call') && main.includes('memory_automation::memory_automation'));
assert(main.includes('provider::memory_provider_key') && shell.includes('worker.shutdown()'));
console.log('Desktop Activity/Usage commands and grants retired; Memory lifecycle retained.');
